// Generates src/icons-paths.ts from src/icons.json using @material-design-icons/svg (filled, 24x24).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "src");
const spec = JSON.parse(readFileSync(join(src, "icons.json"), "utf8"));
const require = createRequire(import.meta.url);
const pkg = dirname(require.resolve("@material-design-icons/svg/package.json"));

function pathOf(file) {
  const svg = readFileSync(join(pkg, "filled", `${file}.svg`), "utf8");
  const ds = [...svg.matchAll(/<path\b([^>]*)\/?>/g)].filter((m) => !/fill="none"/.test(m[1])).map((m) => /\bd="([^"]+)"/.exec(m[1])?.[1]).filter(Boolean);
  if (!ds.length) throw new Error(`no path in ${file}.svg`);
  return ds.join(" ");
}

const entries = Object.entries(spec.icons).sort(([a], [b]) => a.localeCompare(b));
let out = "// Generated by scripts/icons.mjs from src/icons.json; do not edit.\n";
out += `export const FALLBACK = ${JSON.stringify(pathOf(spec.fallback))};\n`;
out += "export const P: Record<string, string> = {\n";
for (const [name, file] of entries) out += `  ${name}: ${JSON.stringify(pathOf(file))},\n`;
out += "};\n";
writeFileSync(join(src, "icons-paths.ts"), out);
console.log(`${entries.length} icons written to src/icons-paths.ts`);
