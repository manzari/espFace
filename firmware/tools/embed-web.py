#!/usr/bin/env python3
"""Gzips web/dist/r/1/app.js and app.css into firmware/src/web/embed.h (PROGMEM arrays) for ESPFACE_EMBED_WEB builds.

Usage: tools/embed-web.py [web/dist/r/1]   (run from firmware/, or pass the dist directory)
"""
import gzip
import sys
from pathlib import Path

here = Path(__file__).resolve().parent
dist = Path(sys.argv[1]) if len(sys.argv) > 1 else here.parent.parent / "web" / "dist" / "r" / "1"
out = here.parent / "src" / "web" / "embed.h"


def gz(path: Path) -> bytes:
    return gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)


def array(name: str, data: bytes) -> str:
    rows = [",".join(f"0x{b:02x}" for b in data[i:i + 32]) for i in range(0, len(data), 32)]
    return f"static const uint8_t {name}[] PROGMEM = {{\n" + ",\n".join(rows) + f"\n}};\nstatic const size_t {name}_LEN = {len(data)};\n"


js, css = gz(dist / "app.js"), gz(dist / "app.css")
out.write_text(
    "#pragma once\n// Generated by tools/embed-web.py from web/dist/r/1. Do not edit; rebuild the web renderer and rerun the tool.\n"
    "#include <stdint.h>\n#include <stddef.h>\n#ifdef ARDUINO\n#include <pgmspace.h>\n#else\n#define PROGMEM\n#endif\n"
    + array("ESPFACE_WEB_JS_GZ", js) + array("ESPFACE_WEB_CSS_GZ", css)
)
print(f"{out}: app.js {len(js)} + app.css {len(css)} bytes gzipped")
