// Copies generated/shared inputs into the site: protocol/PROTOCOL.md -> protocol/index.md, the icon list -> guide/icons-list.md.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const site = join(here, "..");

// Protocol: verbatim, with a note where it comes from. VitePress treats {{ }} as templates; escape them in code.
let proto = readFileSync(join(root, "protocol", "PROTOCOL.md"), "utf8");
proto = proto.replace(/^# espFace protocol v1/, "# Protocol v1");
mkdirSync(join(site, "protocol"), { recursive: true });
writeFileSync(join(site, "protocol", "index.md"), `---\noutline: [2, 3]\n---\n\n::: info Source\nThis page is a copy of \`protocol/PROTOCOL.md\`, the contract shared by the firmware, the web renderer and the app. The JSON schema and the test vectors live next to it in \`protocol/schema/v1\` and \`protocol/vectors\`.\n:::\n\n${proto}`);

// Icon list from the web renderer's source of truth (web/src/icons.json).
const icons = JSON.parse(readFileSync(join(root, "web", "src", "icons.json"), "utf8"));
const names = Object.keys(icons.icons).sort();
let md = `<!-- generated by scripts/prepare.mjs from web/src/icons.json -->\n\n| | | | |\n|---|---|---|---|\n`;
for (let i = 0; i < names.length; i += 4) md += "| " + names.slice(i, i + 4).map((n) => `\`${n}\``).concat(Array(Math.max(0, 4 - names.slice(i, i + 4).length)).fill("")).join(" | ") + " |\n";
md += `\n${names.length} icons. Fallback for unknown names: \`${icons.fallback}\`.\n`;
mkdirSync(join(site, "guide"), { recursive: true });
writeFileSync(join(site, "guide", "icons-list.md"), md);

// Fake device CLI help and widget list are documented by hand; nothing else to copy.
console.log(`prepared protocol page (${proto.length} chars) and ${names.length} icons`);
